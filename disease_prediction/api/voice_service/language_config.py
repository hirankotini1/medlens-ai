# Lookup dict by code
LANGUAGE_MAP: Dict[str, Dict[str, Any]] = {lang["code"]: lang for lang in SUPPORTED_LANGUAGES}


def get_language(code: str) -> Dict[str, Any]:
    """Returns language config for a BCP-47 code, with fallback to English."""
    return LANGUAGE_MAP.get(code, LANGUAGE_MAP["en-IN"])


def get_browser_stt_code(code: str) -> str:
    """Returns the best browser STT locale for the given language code."""
    lang = get_language(code)
    return lang.get("browser_stt_code", "en-IN")


def get_fallback_stt_code(code: str) -> str:
    """Returns the fallback STT code if the primary is unavailable."""
    lang = get_language(code)
    return lang.get("fallback_stt_code", "en-IN")
